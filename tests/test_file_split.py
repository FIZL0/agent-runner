import sys
import tempfile
from pathlib import Path
from unittest import mock

from _check import check, eq, git, report

from agent_runner import config as CF, file_split as F, loop, plan as P, runner as R, status  # noqa: E402

CF.FIXED['merge_ahead'] = False


def project(tmp: Path, lines: list[str], files: dict | None = None, toml: str = '') -> Path:
    repo = Path(tempfile.mkdtemp(dir=tmp))
    git(repo, 'init', '-q', '-b', 'main')
    (repo / 'plan').mkdir()
    (repo / 'plan/TODO.md').write_text('# TODO\n\n### Next\n\n' + ''.join(f'- [ ] **{l}\n' for l in lines), encoding='utf-8')
    (repo / 'plan/DONE.md').write_text('# DONE\n', encoding='utf-8')
    (repo / 'runner.toml').write_text(f'[run]\ntest = "true"\nmin_free_gb = 0\nremote = false\n{toml}', encoding='utf-8')
    (repo / '.gitignore').write_text('.runner/\n', encoding='utf-8')
    for f, text in {'src/a.py': 'a = 1\n', 'tests/test_a.py': '\n', 'b.py': '\n', **(files or {})}.items():
        (repo / f).parent.mkdir(parents=True, exist_ok=True)
        (repo / f).write_text(text, encoding='utf-8')
    git(repo, 'add', '-A')
    git(repo, 'commit', '-qm', 'start')
    R.init(repo)
    return repo


def on(f: str, n: int = 4) -> list[str]:
    return [f'T{i}** task {i} | files: {f}' for i in range(1, n + 1)]


def go(tried=(), slot: str = 'T1', files=None) -> str:
    """A free slot's look while `slot`'s task runs in slot 1."""
    t = {t[0]: t for t in R.tasks('main')}.get(slot) or (slot, 'Next', set(files or ()), set())
    return F.queue_file_split({1: t}, set(tried), 'main', force=True)


def line(repo: Path, tid: str) -> str:
    return next(l for l in P.lines(repo / 'plan/TODO.md') if f'**{tid}**' in l)


def test_trigger(tmp: Path):
    print('3 ready tasks wait for a file and nothing starts: one task to split it')
    repo = project(tmp, on('src/a.py'))
    eq(go(), 'C1', 'queued')
    l = line(repo, 'C1')
    check('(follow-up, critical) (alone) Split `src/a.py` by area: 3 ready tasks waited for it (T2, T3, T4)' in l,
          'critical, alone, and it says who waited', l)
    check('no behaviour change' in l and "narrow the open tasks' files" in l, 'what it asks', l)
    eq(P.fields(l)['files'], ['src/a.py', 'tests/test_a.py'], 'it names the file and its test')
    check(P.alone(l), 'the run reads it as alone')
    eq(P.too_big('C1', R.C, repo / 'plan/TODO.md'), '', 'not over [run] task_size')
    eq(git(repo, 'status', '--porcelain'), '', 'committed')
    eq(git(repo, 'log', '-1', '--format=%s'), 'Plan: C1, split src/a.py', 'as a plan commit')
    check('queued C1 to split src/a.py: 3 ready tasks wait for it (T2, T3, T4)' in R.C.notes('run.log').read_text(),
          'the run log says it')
    ev = json.loads(R.C.notes('events.jsonl').read_text().splitlines()[-1])
    check(ev['kind'] in status.LATELY, 'status lists it')
    eq(status.since_event(ev, {})[1:], ('C1', 'queued C1 to split src/a.py: 3 ready tasks wait for it'), 'and says it')
    eq(R.pick({}, set(), 'main')[0], 'C1', 'it goes first once nothing runs')


def test_no_trigger(tmp: Path):
    print('not for fewer, a task that may start, one held by more than files, or a name that is no tracked file')
    project(tmp, on('src/a.py', 3))
    eq(go(), '', 'two wait')
    project(tmp, [*on('src/a.py'), 'T9** other | files: b.py'])
    eq(go(), '', 'another task may start')
    eq(go(tried={'T9'}), 'C1', 'but not once tried')
    project(tmp, on('src/a.py'))
    eq(go(tried={'T2'}), '', 'a tried task is not ready')
    project(tmp, [f'T{i}** (alone) task {i} | files: src/a.py' for i in range(1, 5)])
    eq(go(), '', 'they run alone anyway')
    project(tmp, on('new.py'))
    eq(go(), '', 'a file that does not exist yet')
    project(tmp, on('a.py'))
    eq(go(), 'C1', 'a tail of a path names the file')
    project(tmp, on('src/*.py'))
    eq(go(slot='X1', files={'src/a.py'}), 'C1', 'a pattern meets the file a running task holds')

    project(tmp, on('src/**'))
    with mock.patch.object(F.sched, 'touched', lambda *_: {'src/a.py'}):
        eq(go(), '', 'two whole-directory globs: no one file holds the tasks')


def test_which_files(tmp: Path):
    print('never a shared, generated, lock, docs or plan file')
    for f, text, toml in (('src/a.py', '', 'shared_files = ["src/a.py"]\n'), ('uv.lock', 'x', ''),
                          ('web/package-lock.json', '{}', ''), ('go.sum', 'x', ''), ('docs/x.html', 'x', ''),
                          ('README.md', 'x', ''), ('doc.tex', 'x', 'docs_files = ["*.tex"]\n'),
                          ('api.py', '# Code generated by x. DO NOT EDIT.\n', ''), ('x_pb2.py', 'x', ''),
                          ('plan/x.json', '{}', '')):
        project(tmp, on(f), {f: text} if text else None, toml)
        eq(go(), '', f)
    project(tmp, on('x.py'), {'x.py': '1\n', '.gitattributes': 'x.py linguist-generated\n'})
    eq(go(), '', 'linguist-generated')


def test_dedupe(tmp: Path):
    print('one open per file, none again within 7 days; another file is free to go')
    repo = project(tmp, on('src/a.py, b.py'))
    todo, done = repo / 'plan/TODO.md', repo / 'plan/DONE.md'
    first = go()
    eq((first, 'Split `b.py`' in line(repo, 'C1')), ('C1', True), 'one a look')
    eq((go(), 'Split `src/a.py`' in line(repo, 'C2')), ('C2', True), 'the other file next')
    eq(go(), '', 'both open: none')
    P.block('C1', 'DECIDE: how?', todo=todo, after=[])
    git(repo, 'commit', '-qam', 'blocked')
    eq(go(), '', 'a blocked one is open')
    P.tick('C1', todo, done)
    git(repo, 'commit', '-qam', 'landed')
    eq(go(), '', 'landed today: none')
    today = dt.date.today()
    for days, want in ((7, ''), (8, 'C3')):
        text = done.read_text()
        now = (today - dt.timedelta(days=days)).isoformat()
        old = P.lines(done)
        stamp = next(F.ci.FILED.search(l)[1] for l in old if 'Split `b.py`' in l)
        done.write_text(text.replace(f'(filed {stamp})', f'(filed {now})'))
        git(repo, 'commit', '-qam', 'aged')
        eq(go(), want, f'{days} days on')


def test_held(tmp: Path):
    print('not while a person edits the plan, nor while a merge has the turn')
    repo = project(tmp, on('src/a.py'))
    todo = repo / 'plan/TODO.md'
    text = todo.read_text()
    todo.write_text(text + '\n')
    eq((go(), todo.read_text()), ('', text + '\n'), 'an edited plan is left alone')
    todo.write_text(text)
    with F.MERGE:
        eq(go(), '', 'a merge has the turn')
    eq(go(), 'C1', 'then it is queued')


def test_kinds(tmp: Path):
    print('the kind: C where the kinds have it')
    project(tmp, on('src/a.py'), toml='[plan.kinds]\nX = "work"\nT = "tests"\n')
    eq(go(), 'X1', "a repo's own kinds without C")


def test_switch(tmp: Path):
    print('[run] split_files: on by default, off queues none')
    repo = project(tmp, on('src/a.py'))
    eq(R.C.run['split_files'], True, 'on by default')
    eq(CF.setting_type('run', 'split_files'), 'switch', 'a switch')
    (repo / 'runner.toml').write_text('[run]\nsplit_files = false\n')
    with mock.patch.dict(R.C.run, split_files=CF.Config(repo).run['split_files']):
        eq(go(), '', 'off')
    eq(R.open_tasks('main'), {'T1', 'T2', 'T3', 'T4'}, 'nothing filed')
    (repo / 'runner.toml').write_text('[run]\nsplit_files = "no"\n')
    try:
        CF.Config(repo)
        check(False, 'a word is refused')
    except SystemExit as e:
        check('[run] split_files must be true or false' in str(e), 'a word is refused', e)


def test_fill(tmp: Path):
    print('the run asks when its free slot has no task, and looks at most once a minute')
    project(tmp, on('src/a.py'))
    run = loop.Run(mock.Mock(), 2, False, 'main', '', 30, 20, 5)
    run.procs, run.running = {1: mock.Mock()}, {1: {t[0]: t for t in R.tasks('main')}['T1']}
    F.LOOKED[0] = 0.0
    with mock.patch.object(loop, 'capped', lambda *_: None), mock.patch.object(loop, 'api_down', lambda *_: False), \
            mock.patch.object(loop, 'low_disk', lambda *_: False):
        run.fill(2)
        splits = [t for t in R.open_tasks('main') if t.startswith('C')]
        eq(splits, ['C1'], 'queued from fill')
        with mock.patch.object(F.sched, 'held', side_effect=AssertionError):
            eq(F.queue_file_split(run.running, set(), 'main'), '', 'the next look waits')


def main() -> int:
    with tempfile.TemporaryDirectory() as d:
        os.environ['CLAUDE_CONFIG_DIR'] = d
        tmp = Path(d)
        return report([lambda f=f: f(tmp) for f in (test_trigger, test_no_trigger, test_which_files, test_dedupe,
                                                    test_held, test_kinds, test_switch, test_fill)])


if __name__ == '__main__':
    sys.exit(main())
